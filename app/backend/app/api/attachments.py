router = APIRouter(prefix="/api", tags=["attachments"])

MAX_IMAGE = 10 * 1024 * 1024
MAX_PDF = 20 * 1024 * 1024
OWNERS = {"visit": (VehicleVisit, "visits"), "vehicle": (Vehicle, "vehicles"), "part": (PartPurchase, "visits"),
          "workshop": (None, "settings")}  # the workshop logo


def sniff(head: bytes) -> tuple[str, str] | None:
    """Detect the real file type from its first bytes (the client-supplied name/type is never trusted)."""
    if head.startswith(b"\xff\xd8\xff"):
        return "image/jpeg", "jpg"
    if head.startswith(b"\x89PNG\r\n\x1a\n"):
        return "image/png", "png"
    if head[:4] == b"RIFF" and head[8:12] == b"WEBP":
        return "image/webp", "webp"
    if head[:6] in (b"GIF87a", b"GIF89a"):
        return "image/gif", "gif"
    if head.startswith(b"%PDF-"):
        return "application/pdf", "pdf"
    return None


def clean_name(name: str) -> str:
    base = re.split(r"[\\/]", name or "file")[-1]
    base = re.sub(r"[\x00-\x1f<>:\"|?*]", "_", base).strip(". ")
    return base[:120] or "file"


def root() -> Path:
    return get_settings().storage_dir / "attachments"


def _owner(db: DbSession, owner_type: str, owner_id: str):
    if owner_type not in OWNERS:
        raise AppError("نوع السجل غير مدعوم", 422, "bad_owner_type")
    model, _ = OWNERS[owner_type]
    if owner_type == "workshop":
        if owner_id != "logo":
            raise AppError("السجل المرتبط غير موجود", 404, "owner_not_found")
        return None
    key = int(owner_id) if owner_type == "part" and owner_id.isdigit() else owner_id
    try:
        obj = db.get(model, key)
    except Exception:  # noqa: BLE001 - malformed id
        obj = None
    if not obj:
        raise AppError("السجل المرتبط غير موجود", 404, "owner_not_found")
    return obj


def _need(user: User, owner_type: str, write: bool) -> None:
    group = OWNERS[owner_type][1]
    if group == "settings":  # anyone signed in may see the logo; only settings managers may change it
        if write and "settings.manage" not in user.permissions:
            raise AppError("ليس لديك صلاحية لهذا الإجراء", 403, "forbidden")
        return
    perm = f"{group}.write" if write else f"{group}.read"
    if perm not in user.permissions:
        raise AppError("ليس لديك صلاحية لهذا الإجراء", 403, "forbidden")


def out(a: Attachment) -> dict:
    return {"id": str(a.id), "owner_type": a.owner_type, "owner_id": a.owner_id, "kind": a.kind, "point": a.point,
            "name": a.original_name, "mime": a.mime, "size_bytes": a.size_bytes, "note": a.note,
            "uploaded_at": a.uploaded_at, "url": f"/api/attachments/{a.id}/file"}


@router.post("/attachments", status_code=201)
async def upload(request: Request, owner_type: str = Form(...), owner_id: str = Form(...), kind: str = Form("photo"),
                 point: str | None = Form(None), note: str | None = Form(None), file: UploadFile = File(...),
                 user: User = Depends(current_user), db: DbSession = Depends(get_db, scope="function")):
    if owner_type not in OWNERS:
        raise AppError("نوع السجل غير مدعوم", 422, "bad_owner_type")
    _need(user, owner_type, write=True)
    if kind not in ("photo", "document"):
        raise AppError("نوع المرفق غير صحيح", 422, "bad_kind")
    _owner(db, owner_type, owner_id)
    head = await file.read(16)
    found = sniff(head)
    if not found:
        raise AppError("نوع الملف غير مسموح (صور JPG/PNG/WEBP/GIF أو PDF فقط)", 422, "bad_type")
    mime, ext = found
    if kind == "photo" and mime == "application/pdf":
        raise AppError("الصور يجب أن تكون بصيغة صورة", 422, "bad_type")
    limit = MAX_PDF if mime == "application/pdf" else MAX_IMAGE
    folder = root() / datetime.now(timezone.utc).strftime("%Y/%m")
    folder.mkdir(parents=True, exist_ok=True)
    rel = f"{folder.relative_to(root()).as_posix()}/{uuid.uuid4().hex}.{ext}"  # name generated by us, never by the client
    dest = root() / rel
    h, size = hashlib.sha256(head), len(head)
    try:
        with open(dest, "wb") as out_f:
            out_f.write(head)
            while True:
                chunk = await file.read(1024 * 1024)
                if not chunk:
                    break
                size += len(chunk)
                if size > limit:
                    raise AppError(f"حجم الملف أكبر من المسموح ({limit // 2**20} ميجا)", 413, "too_large")
                h.update(chunk)
                out_f.write(chunk)
    except BaseException:
        dest.unlink(missing_ok=True)
        raise
    a = Attachment(owner_type=owner_type, owner_id=owner_id, kind=kind, point=(point or None), original_name=clean_name(file.filename or ""),
                   stored_path=rel, mime=mime, size_bytes=size, sha256=h.hexdigest(), note=note, uploaded_by=user.id)
    db.add(a)
    db.flush()
    audit(db, user, "attachment.upload", owner_type, owner_id, after={"id": str(a.id), "name": a.original_name, "size": size},
          ip=client_ip(request))
    return out(a)


@router.get("/attachments")
def list_attachments(owner_type: str, owner_id: str, user: User = Depends(current_user), db: DbSession = Depends(get_db, scope="function")):
    if owner_type not in OWNERS:
        raise AppError("نوع السجل غير مدعوم", 422, "bad_owner_type")
    _need(user, owner_type, write=False)
    rows = db.scalars(select(Attachment).where(Attachment.owner_type == owner_type, Attachment.owner_id == owner_id,
                                               Attachment.is_removed.is_(False)).order_by(Attachment.uploaded_at))
    return [out(a) for a in rows]


@router.get("/attachments/{att_id}/file")
def get_file(att_id: uuid.UUID, user: User = Depends(current_user), db: DbSession = Depends(get_db, scope="function")):
    a = db.get(Attachment, att_id)
    if not a or a.is_removed:
        raise AppError("الملف غير موجود", 404, "not_found")
    _need(user, a.owner_type, write=False)
    p = (root() / a.stored_path).resolve()
    if root().resolve() not in p.parents or not p.is_file():
        raise AppError("الملف غير موجود", 404, "not_found")
    headers = {"X-Content-Type-Options": "nosniff", "Content-Security-Policy": "sandbox; default-src 'none'",
               "Cache-Control": "private, max-age=3600"}
    return FileResponse(p, media_type=a.mime, headers=headers, content_disposition_type="inline", filename=None)


class RemoveIn(BaseModel):
    reason: str = Field(min_length=3)


@router.post("/attachments/{att_id}/remove")
def remove(att_id: uuid.UUID, body: RemoveIn, request: Request, user: User = Depends(current_user), db: DbSession = Depends(get_db, scope="function")):
    a = db.get(Attachment, att_id)
    if not a or a.is_removed:
        raise AppError("الملف غير موجود", 404, "not_found")
    _need(user, a.owner_type, write=True)
    a.is_removed, a.removed_reason = True, body.reason  # the file stays on disk (and in backups); only hidden
    audit(db, user, "attachment.remove", a.owner_type, a.owner_id, before={"id": str(a.id), "name": a.original_name},
          reason=body.reason, ip=client_ip(request))
    return {"ok": True}
